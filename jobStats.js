// 根据职业和等级查询基础属性（线性插值）
function getJobBaseStats(job, level) {
  const table = JOB_GROWTH[job];
  if (!table) return { hp: 30, mp: 5, minAtk: 0, maxAtk: 0, minDef: 0, maxDef: 0, minMagDef: 0, maxMagDef: 0, minMagAtk: 0, maxMagAtk: 0 };
  if (level <= 1) {
    const r = table[0];
    return { hp: r[1], mp: r[2], minAtk: r[3], maxAtk: r[4], minDef: r[5], maxDef: r[6], minMagDef: r[7], maxMagDef: r[8], minMagAtk: r[9], maxMagAtk: r[10] };
  }
  if (level >= 260) {
    const r = table[table.length - 1];
    return { hp: r[1], mp: r[2], minAtk: r[3], maxAtk: r[4], minDef: r[5], maxDef: r[6], minMagDef: r[7], maxMagDef: r[8], minMagAtk: r[9], maxMagAtk: r[10] };
  }
  // 找到区间并插值
  let lo = table[0], hi = table[table.length - 1];
  for (let i = 0; i < table.length - 1; i++) {
    if (level >= table[i][0] && level <= table[i + 1][0]) {
      lo = table[i]; hi = table[i + 1]; break;
    }
  }
  const t = (level - lo[0]) / (hi[0] - lo[0]);
  const lerp = (a, b) => Math.floor(a + (b - a) * t);
  return {
    hp: lerp(lo[1], hi[1]),
    mp: lerp(lo[2], hi[2]),
    minAtk: lerp(lo[3], hi[3]),
    maxAtk: lerp(lo[4], hi[4]),
    minDef: lerp(lo[5], hi[5]),
    maxDef: lerp(lo[6], hi[6]),
    minMagDef: lerp(lo[7], hi[7]),
    maxMagDef: lerp(lo[8], hi[8]),
    minMagAtk: lerp(lo[9], hi[9]),
    maxMagAtk: lerp(lo[10], hi[10]),
  };
}
